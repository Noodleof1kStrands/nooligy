#!/bin/sh
set -eu

script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_root=$(dirname -- "$script_dir")
cd "$repo_root"

output=docs/module-tree.md
mkdir -p docs

{
  printf '%s\n' '<!-- Generated by scripts/gen-module-tree.sh. Do not edit by hand. -->'
  printf '\n'
  printf '%s\n\n' '# Module tree'
  printf '%s\n' 'Every file under `modules/`, grouped by top-level directory and sorted.'
  printf '%s\n' 'Regenerate with `sh scripts/gen-module-tree.sh`; CI fails when this file'
  printf '%s\n' 'differs from the generator output.'
  printf '\n'

  current_group=
  find modules -type f | LC_ALL=C sort | while IFS= read -r file_path; do
    relative_path=${file_path#modules/}
    case $relative_path in
      */*) group=${relative_path%%/*} ;;
      *) group=. ;;
    esac

    if [ "$group" != "$current_group" ]; then
      [ -z "$current_group" ] || printf '\n'
      if [ "$group" = . ]; then
        printf '## `modules/`\n\n'
      else
        printf '## `%s`\n\n' "$group"
      fi
      current_group=$group
    fi

    printf -- '- `%s`\n' "$file_path"
  done
} > "$output"

printf 'wrote %s\n' "$output"
